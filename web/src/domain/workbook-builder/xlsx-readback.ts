import * as XLSX from "xlsx";
import { normalizeCellAddress } from "../formula-compiler/reference-codec";
import type { XLSXWorkbookSpec } from "./serialization";

const MAX_GENERATED_BYTES = 64 * 1024 * 1024;
const MAX_GRID_SLOTS = 1_000_000;
type Result =
  { readonly ok: true } | { readonly ok: false; readonly message: string };
type ExpectedCell =
  | { readonly kind: "value"; readonly value: string | number | boolean }
  | { readonly kind: "formula"; readonly formula: string };

/** Bounds dense rows and formula targets before the writer allocates XLSX data. */
export function preflightXlsxSpec(spec: XLSXWorkbookSpec): Result {
  try {
    let slots = 0;
    for (const sheet of spec.sheets) {
      slots += sheet.formulas?.length ?? 0;
      for (const [rowIndex, row] of sheet.rows.entries()) {
        slots += row.length;
        if (row.length > 0 && (rowIndex >= 1_048_576 || row.length > 16_384))
          return {
            ok: false,
            message: "Generated workbook has a grid outside Excel limits.",
          };
        if (slots > MAX_GRID_SLOTS)
          return {
            ok: false,
            message: "Generated workbook exceeds the read-back grid limit.",
          };
      }
      if (slots > MAX_GRID_SLOTS)
        return {
          ok: false,
          message: "Generated workbook exceeds the read-back grid limit.",
        };
    }
    return { ok: true };
  } catch {
    return {
      ok: false,
      message: "Generated workbook grid could not be checked safely.",
    };
  }
}

/**
 * Checks generated-in-memory bytes against the serializer's spec. Do not use
 * this as an arbitrary XLSX upload parser or ZIP-bomb defense. This uses the
 * same library as the writer and is not independent execution or approval.
 */
export function verifyGeneratedXlsx(
  spec: XLSXWorkbookSpec,
  bytes: Uint8Array,
): Result {
  const fail = (message: string): Result => ({ ok: false, message });
  try {
    if (bytes.length === 0 || bytes.length > MAX_GENERATED_BYTES)
      return fail(
        "Generated workbook is empty or exceeds the read-back size limit.",
      );
    const preflight = preflightXlsxSpec(spec);
    if (!preflight.ok) return preflight;
    const expectedSheets = new Map<
      string,
      { cells: Map<string, ExpectedCell>; range: XLSX.Range | null }
    >();
    for (const sheet of spec.sheets) {
      if (expectedSheets.has(sheet.name))
        return fail("Generated workbook sheet names are ambiguous.");
      const cells = new Map<string, ExpectedCell>();
      let range: XLSX.Range | null = null;
      for (const [rowIndex, row] of sheet.rows.entries()) {
        if (row.length > 0) {
          if (range === null)
            range = {
              s: { r: 0, c: 0 },
              e: { r: rowIndex, c: row.length - 1 },
            };
          else {
            range.e.r = Math.max(range.e.r, rowIndex);
            range.e.c = Math.max(range.e.c, row.length - 1);
          }
        }
        for (const [columnIndex, value] of row.entries()) {
          if (value === null) continue;
          if (
            (typeof value !== "string" &&
              typeof value !== "boolean" &&
              typeof value !== "number") ||
            (typeof value === "number" && !Number.isFinite(value))
          )
            return fail("Generated workbook has an unsupported cell value.");
          const address = XLSX.utils.encode_cell({
            r: rowIndex,
            c: columnIndex,
          });
          if (normalizeCellAddress(address) === null)
            return fail("Generated workbook has a cell outside Excel limits.");
          cells.set(address, { kind: "value", value });
        }
      }
      for (const formula of sheet.formulas ?? []) {
        const address = normalizeCellAddress(formula.address)?.replaceAll(
          "$",
          "",
        );
        if (
          address === undefined ||
          cells.has(address) ||
          !formula.formulaText.startsWith("=") ||
          formula.formulaText.slice(1).trim() === ""
        )
          return fail(
            "Generated workbook has an invalid or duplicate formula target.",
          );
        cells.set(address, {
          kind: "formula",
          formula: formula.formulaText.slice(1),
        });
        const point = XLSX.utils.decode_cell(address);
        if (range === null) range = { s: { ...point }, e: { ...point } };
        else {
          range.s.r = Math.min(range.s.r, point.r);
          range.s.c = Math.min(range.s.c, point.c);
          range.e.r = Math.max(range.e.r, point.r);
          range.e.c = Math.max(range.e.c, point.c);
        }
      }
      expectedSheets.set(sheet.name, { cells, range });
    }
    // SheetJS can attach parser properties to its input. Keep generated bytes
    // untouched for hashing and download.
    const parsed = XLSX.read(new Uint8Array(bytes), {
      type: "array",
      sheetStubs: true,
      cellFormula: true,
    });
    if (
      parsed.SheetNames.length !== spec.sheets.length ||
      parsed.SheetNames.some((name, index) => name !== spec.sheets[index]?.name)
    )
      return fail(
        "Generated workbook sheet inventory does not match its model.",
      );
    for (const [index, sheet] of spec.sheets.entries()) {
      const actual = parsed.Sheets[sheet.name];
      const expectedSheet = expectedSheets.get(sheet.name);
      if (
        !actual ||
        !expectedSheet ||
        (parsed.Workbook?.Sheets?.[index]?.Hidden ?? 0) !==
          (sheet.hidden ? 1 : 0)
      )
        return fail(
          "Generated workbook sheet visibility or content does not match its model.",
        );
      const { cells, range } = expectedSheet;
      if (
        (actual["!ref"] ?? null) !==
        (range === null ? null : XLSX.utils.encode_range(range))
      )
        return fail(
          "Generated workbook worksheet dimensions do not match its model.",
        );
      const actualAddresses = Object.keys(actual).filter(
        (key) => !key.startsWith("!"),
      );
      if (actualAddresses.length !== cells.size)
        return fail(
          "Generated workbook cell inventory does not match its model.",
        );
      for (const address of actualAddresses) {
        const expected = cells.get(address);
        const cell = actual[address] as XLSX.CellObject | undefined;
        if (!expected || !cell)
          return fail("Generated workbook has an unexpected cell.");
        if (expected.kind === "formula") {
          // SheetJS exposes uncached stubs as type z and may report v=0 even
          // though no cached result was written. Never treat it as a result.
          if (cell.f !== expected.formula || cell.t !== "z")
            return fail(
              "Generated workbook formula or cached value does not match its model.",
            );
        } else if (
          cell.f !== undefined ||
          cell.v !== expected.value ||
          cell.t !==
            (typeof expected.value === "string"
              ? "s"
              : typeof expected.value === "boolean"
                ? "b"
                : "n")
        )
          return fail(
            "Generated workbook cell value does not match its model.",
          );
      }
    }
    const expectedNames = spec.namedRanges.map((name) => ({
      name: name.name,
      ref: name.reference,
      sheet:
        name.scope === "sheet"
          ? spec.sheets.findIndex((sheet) => sheet.name === name.sheetName)
          : null,
    }));
    if (expectedNames.some((name) => name.sheet === -1))
      return fail("Generated workbook has an invalid named-range scope.");
    const names = parsed.Workbook?.Names ?? [];
    if (names.length !== expectedNames.length)
      return fail(
        "Generated workbook named-range inventory does not match its model.",
      );
    for (const [index, expected] of expectedNames.entries()) {
      const actual = names[index];
      if (
        actual?.Name !== expected.name ||
        actual.Ref !== expected.ref ||
        (actual.Sheet ?? null) !== expected.sheet
      )
        return fail("Generated workbook named range does not match its model.");
    }
    return { ok: true };
  } catch {
    return fail("Generated workbook could not be read back safely.");
  }
}
